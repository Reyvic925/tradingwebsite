import assert from 'node:assert/strict';
import { getInstrument, positionPnl, validQuantity, orderPreview } from '../../shared/trading-instruments.js';
import { marketSession, dayExpiry, parseZonedExpiry } from '../../shared/trading-sessions.js';

const stock=getInstrument('AAPL'),gold=getInstrument('GC=F'),btc=getInstrument('BTCUSD'),fx=getInstrument('USDJPY');
assert.equal(marketSession(stock,new Date('2026-11-12T14:29:59Z')).open,false);
assert.equal(marketSession(stock,new Date('2026-11-12T14:30:00Z')).open,true);
assert.equal(marketSession(stock,new Date('2026-11-12T21:00:00Z')).open,false);
assert.equal(marketSession(stock,new Date('2026-11-26T16:00:00Z')).open,false,'Thanksgiving');
assert.equal(marketSession(stock,new Date('2026-11-27T17:59:00Z')).open,true);
assert.equal(marketSession(stock,new Date('2026-11-27T18:00:00Z')).open,false,'early close is 1 pm New York');
assert.equal(dayExpiry(stock,new Date('2026-11-27T16:00:00Z')),'2026-11-27T18:00:00.000Z');
assert.equal(dayExpiry(stock,new Date('2026-11-27T19:00:00Z')),'2026-11-30T21:00:00.000Z');
assert.equal(marketSession(stock,new Date('2026-03-09T13:30:00Z')).open,true,'DST moves opening UTC time');
assert.equal(marketSession(stock,new Date('2026-03-06T13:30:00Z')).open,false);
assert.equal(marketSession(stock,new Date('2027-12-31T15:00:00Z')).open,true,'NYSE does not observe Saturday New Year on preceding Friday');
assert.equal(marketSession(stock,new Date('2030-11-12T15:00:00Z')).open,false,'do not guess beyond published calendar coverage');
assert.equal(marketSession(btc,new Date('2026-11-14T03:00:00Z')).open,true,'crypto is 24/7');
assert.equal(dayExpiry(btc,new Date('2026-11-14T03:00:00Z')),'2026-11-15T00:00:00.000Z');
assert.equal(marketSession(fx,new Date('2026-11-15T21:59:00Z')).open,false);
assert.equal(marketSession(fx,new Date('2026-11-15T22:00:00Z')).open,true);
assert.equal(marketSession(gold,new Date('2026-11-12T22:30:00Z')).open,false,'Globex daily maintenance');
assert.equal(marketSession(gold,new Date('2026-11-12T23:01:00Z')).open,true);
assert.equal(marketSession(getInstrument('7203.T'),new Date('2026-11-12T03:00:00Z')).timezone,'Asia/Tokyo');
assert.equal(parseZonedExpiry('2026-11-12T15:30','America/New_York'),'2026-11-12T20:30:00.000Z');
assert.throws(()=>parseZonedExpiry('2026-03-08T02:30','America/New_York'),/does not exist/);
assert.equal(getInstrument('ES=F').multiplier,50);
assert.equal(btc.tick,.01,'Coinbase BTC price increments are cents, not an invented universal crypto tick');
assert.equal(getInstrument('SHIBUSD').quantity_step,1,'whole-token size increment is enforced when specified by provider');
assert.equal(gold.multiplier,100);
assert.equal(positionPnl({entry_price:2000,quantity:2,contract_multiplier:100,side:'long'},2001,1),200);
assert.equal(validQuantity(.5,gold),false,'fractional futures contracts are invalid');
assert.equal(validQuantity(2,gold),true);
const preview=orderPreview({instrument:stock,price:100,quantity:10,side:'buy',stopLoss:95,takeProfit:110,equity:10000,commissionBps:10,rate:1});
assert.equal(preview.risk_at_stop,50);assert.equal(preview.reward_to_risk,2);assert.equal(preview.entry_fee,1);
console.log('TRADING_SESSIONS_TESTS_PASSED');
