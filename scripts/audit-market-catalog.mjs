function candidates(row, meta) {
  const s = row.symbol.toUpperCase();
  if (s === '10Y=F' || s === '30Y=F') return ['CBOT','CME','CBOT_MINI','CME_MINI'].map((ex) => `${ex}:${s.replace('=F','1!')}`);
  if (/^X(AU|AG|PT|PD)USD$/.test(s)) return [`OANDA:${s}`,`TVC:${s}`];
  if (row.asset_class === 'crypto') return [`COINBASE:${s}`];
  if (tvIndices[s]) return [tvIndices[s]];
  if (tvFutures[s.replace(/=F$/, '')]) return [tvFutures[s.replace(/=F$/, '')]];
  if (row.asset_class === 'forex') return [`OANDA:${s}`,`FX_IDC:${s}`,`FX:${s}`];
  const suffixes = { '.T':['TSE'],'.TO':['TSX'],'.L':['LSE'],'.DE':['XETR','FWB'],'.PA':['EURONEXT'],'.NS':['NSE'],'.BO':['BSE'],'.MI':['MIL'],'.AS':['EURONEXT'],'.BR':['EURONEXT'],'.HK':['HKEX'],'.SW':['SIX'],'.MC':['BME'],'.ST':['OMXSTO'],'.CO':['OMXCOP'],'.HE':['OMXHEX'],'.OL':['OSL'] };
  for (const [suffix, exchanges] of Object.entries(suffixes)) {
    if (s.endsWith(suffix)) {
      const base = s.slice(0,-suffix.length);
      const names = [base,base.replace(/-/g,'.'),base.replace(/-/g,'_'),...(suffix === '.L' ? [`${base}.`] : [])];
      return exchanges.flatMap((ex) => [...new Set(names)].map((name) => `${ex}:${name}`));
    }
  }
  const exchange = {NMS:'NASDAQ',NGM:'NASDAQ',NCM:'NASDAQ',NYQ:'NYSE',PCX:'AMEX',ASE:'AMEX',BTS:'CBOE'}[meta?.exchangeName];
  return [...new Set([exchange,'NASDAQ','NYSE','AMEX','CBOE'].filter(Boolean))].map((ex) => `${ex}:${s.replace(/-/g,'.')}`);
}
async function inspect(row) {
  const item = { ...row, audited_at: new Date().toISOString(), status: 'unverified' };
  if (/^[A-Z]{3}\d{2}$/.test(row.symbol) && row.name === `${row.symbol} Holdings`) {
    return { ...item, status: 'fabricated', reason: 'Generated by EXTRA_STOCKS in universe-data.js; not an exchange listing.', candidates: [] };
  }
  let meta;
  if (row.asset_class === 'crypto') {
    const product = productMap.get(row.symbol.replace(/USD$/, '-USD'));
    item.provider = 'Coinbase';
    item.provider_symbol = product?.id;
    item.provider_confirmed = Boolean(product && product.status === 'online' && !product.trading_disabled);
    item.reason = item.provider_confirmed ? null : 'No active Coinbase USD product (not proof the asset is fictitious).';
    item.currency = product?.quote_currency;
  } else if (/^X(AU|AG|PT|PD)USD$/.test(row.symbol)) {
    item.provider = 'Gold API';
    item.provider_symbol = row.symbol.slice(0,3);
    try {
      const data = await json(`https://api.gold-api.com/price/${item.provider_symbol}`);
      item.provider_confirmed = data.symbol === item.provider_symbol && Number(data.price) > 0;
      item.currency = data.currency || 'USD';
      item.provider_name = data.name;
    } catch(e) { item.reason = e.message; }
  } else {
    item.provider = 'Yahoo Finance';
    item.provider_symbol = indexMap[row.symbol] || (futures.has(row.symbol) ? `${row.symbol}=F` : row.asset_class === 'forex' ? `${row.symbol}=X` : row.symbol);
    for (let attempt = 0; attempt < 2; attempt++) {
      try {
        const data = await json(`https://query1.finance.yahoo.com/v8/finance/chart/${encodeURIComponent(item.provider_symbol)}?interval=1d&range=5d`);
        meta = data.chart?.result?.[0]?.meta;
        item.provider_confirmed = Boolean(meta?.symbol && Number(meta.regularMarketPrice) > 0);
        item.currency = meta?.currency;
        item.provider_name = meta?.longName || meta?.shortName;
        item.provider_exchange = meta?.exchangeName;
        item.provider_timestamp = meta?.regularMarketTime;
        item.reason = item.provider_confirmed ? null : 'Provider did not return an instrument quote.';
        break;
      } catch(e) {
        item.reason = e.message;
        if (![429,500,502,503,504].includes(e.status)) break;
        await pause(2500);
      }
    }
  }
  item.candidates = candidates(row,meta);
  item.status = item.provider_confirmed ? 'provider_verified' : 'provider_unsupported_or_unverified';
  return item;
}
