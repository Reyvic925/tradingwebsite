import fs from 'node:fs';

const audited = JSON.parse(fs.readFileSync('tmp/market-catalog-audit.json', 'utf8'));
const input = JSON.parse(fs.readFileSync('tmp/market-catalog-input.json', 'utf8'));
const products=fs.existsSync('tmp/coinbase-products-audit.json')?JSON.parse(fs.readFileSync('tmp/coinbase-products-audit.json','utf8')):[];
const increments=new Map(products.map(product=>[product.id,product]));
for(const row of audited.filter(row=>row.active&&row.provider==='Coinbase')) {
  const product=increments.get(row.provider_symbol);
  if(!(Number(product?.quote_increment)>0&&Number(product?.base_increment)>0))throw new Error(`Refresh Coinbase increment metadata before publishing ${row.symbol}.`);
}
// Quote-only markets are real and chart-supported. Keep them visible; block
// execution until their native currency can be settled in the USD ledger.
for (const row of audited) {
  if (row.status === 'currency_unsupported') { row.active = true; row.status = 'verified_quote_only'; }
}
if (audited.length !== input.length || audited.some((row) => !Object.hasOwn(row, 'active'))) {
  throw new Error('The provider and TradingView audit must finish before building a catalog.');
}
const verified = audited.filter((row) => row.active).map((row) => ({
  symbol: row.symbol,
  name: (row.asset_class === 'futures' ? row.tradingview_description : row.provider_name) || row.tradingview_description || row.name,
  asset_class: row.asset_class,
  provider: row.provider,
  provider_symbol: row.provider_symbol,
  tradingview_symbol: row.tradingview_symbol,
  currency: row.currency,
  currency_supported: row.currency_supported,
  quote_increment:row.provider==='Coinbase'?Number(increments.get(row.provider_symbol)?.quote_increment)||undefined:undefined,
  quantity_increment:row.provider==='Coinbase'?Number(increments.get(row.provider_symbol)?.base_increment)||undefined:undefined,
}));
const source = `// Generated by scripts/build-verified-market-catalog.mjs from a completed provider/TradingView audit.\nexport const VERIFIED_MARKETS = ${JSON.stringify(verified,null,2)};\n`;
fs.mkdirSync('shared/market-catalog', { recursive: true });
fs.writeFileSync('shared/market-catalog/verified.js', source);
fs.mkdirSync('docs/market-catalog', { recursive: true });
fs.writeFileSync('docs/market-catalog/audit.json', JSON.stringify(audited,null,2));
const counts = audited.reduce((all,row) => (all[row.status]=(all[row.status]||0)+1,all),{});
fs.writeFileSync('docs/market-catalog/summary.json',JSON.stringify({audited_at:new Date().toISOString(),total:audited.length,selectable:verified.length,statuses:counts},null,2));
console.log(JSON.stringify({total:audited.length,selectable:verified.length,statuses:counts}));
