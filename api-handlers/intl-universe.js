function r(symbol, name, asset_class, price, volume) {
  const ch = Number((Math.sin(symbol.length * 2.1 + price) * 1.4).toFixed(2));
  return {
    symbol,
    name,
    asset_class,
    price,
    change_24h: ch,
    volume,
    high_24h: Number((price * 1.016).toFixed(4)),
    low_24h: Number((price * 0.984).toFixed(4)),
  };
}

