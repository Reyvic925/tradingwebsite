function row(symbol, name, asset_class, price, volume) {
  const ch = Number(((Math.sin(symbol.length * 1.7) * 1.8)).toFixed(2));
  return {
    symbol,
    name,
    asset_class,
    price,
    change_24h: ch,
    volume,
    high_24h: Number((price * 1.018).toFixed(4)),
    low_24h: Number((price * 0.982).toFixed(4)),
  };
}

